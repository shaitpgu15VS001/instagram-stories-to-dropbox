from playwright.sync_api import sync_playwright

p = sync_playwright().start()
try:
    b = p.chromium.launch(headless=True, args=['--no-sandbox', '--disable-dev-shm-usage'])
    c = b.new_context(user_agent='Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36', viewport={'width': 1280, 'height': 900}, locale='en-US')
    page = c.new_page()
    page.goto('https://fastdl.app/en2/instagram-anonymously-viewer', wait_until='domcontentloaded', timeout=60000)
    page.wait_for_selector('#search-form-input', timeout=30000, state='visible')
    print('initial url', page.url)
    print('initial title', page.title())
    print('search visible', page.is_visible('#search-form-input'))
    print('button exists', bool(page.query_selector('#searchFormButton')))
    print('button text', page.query_selector('#searchFormButton').inner_text())
    print('button outer', page.query_selector('#searchFormButton').evaluate('e => e.outerHTML'))
    print('input outer', page.query_selector('#search-form-input').evaluate('e => e.outerHTML'))
    print('button disabled', page.query_selector('#searchFormButton').get_attribute('disabled'))
    print('button css pointer-events', page.query_selector('#searchFormButton').evaluate('e => window.getComputedStyle(e).pointerEvents'))
    print('has form', bool(page.query_selector('form')))
    print('form outer', page.query_selector('form').evaluate('e=>e.outerHTML') if page.query_selector('form') else 'none')
    page.fill('#search-form-input', 'israel_bidur')
    page.wait_for_timeout(500)
    print('after fill button disabled', page.query_selector('#searchFormButton').get_attribute('disabled'))
    print('after fill button css pointer-events', page.query_selector('#searchFormButton').evaluate('e => window.getComputedStyle(e).pointerEvents'))
    print('input value', page.query_selector('#search-form-input').evaluate('e => e.value'))
    print('clicking button...')
    page.click('#searchFormButton', force=True, timeout=30000)
    page.wait_for_timeout(3000)
    print('after click url', page.url)
    print('after click title', page.title())
    print('tab buttons:', [e.inner_text().strip() for e in page.query_selector_all('button.tabs-component__button')])
    print('content html snippet', page.query_selector('body').evaluate('e => e.innerText.slice(0,400)'))
    page.screenshot(path='scripts/debug_investigate_after_click.png')
    b.close()
finally:
    p.stop()
